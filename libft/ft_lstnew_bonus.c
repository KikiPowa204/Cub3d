#include "libft.h"

t_stack	*ft_lstnew(int content)
{
	t_stack	*new;

	new = malloc(sizeof(t_stack));
	if (!new)
		return (0);
	new->num = content;
	new->index = 0;
	new->next = 0;
	return (new);
}
